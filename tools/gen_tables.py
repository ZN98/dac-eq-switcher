#!/usr/bin/env python3
"""Generate src/ToppingTables.g.cs from a toppingctl checkout.

Usage: gen_tables.py <toppingctl dir> <git revision> <output .cs>

Everything the app knows about Topping models, the DX5 II settings map and
the value names comes from toppingctl's own tables, so the app stays within
what toppingctl supports.
"""

import importlib
import sys
import types


def cs(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src, rev, out = sys.argv[1:4]
    sys.modules.setdefault("hid", types.ModuleType("hid"))  # not needed for tables
    sys.path.insert(0, src)
    tc = importlib.import_module("toppingctl")
    vc = importlib.import_module("vendor_commands")
    sc = importlib.import_module("setctl")
    scenes = importlib.import_module("scenes")

    lines = [
        "// <auto-generated> from toppingctl (github.com/gjcourt/toppingctl, Apache-2.0)",
        f"// revision {rev} by tools/gen_tables.py. Do not edit by hand.",
        "using System.Collections.Generic;",
        "",
        "namespace DacEqSwitcher",
        "{",
        "    static class ToppingTables",
        "    {",
        f"        public const string Revision = {cs(rev[:7])};",
        "",
        "        public static readonly ModelInfo[] Models =",
        "        {",
    ]
    for key, d in tc.DEVICES.items():
        if d.get("protocol") == "dx1":
            proto = "Dx1"
        elif key == "dx5ii":
            proto = "Dx5"  # the GetSettings map in vendor_commands is the DX5 II's
        else:
            proto = "None"  # toppingctl has no confirmed settings read for it
        match = ", ".join(cs(m) for m in d.get("product_match", ()))
        lines.append(
            f"            new ModelInfo({cs(key)}, {cs(d['name'])}, 0x{d['vid']:04X}, 0x{d['pid']:04X}, "
            f"new[] {{ {match} }}, Protocol.{proto}),"
        )
    lines += ["        };", "", f"        public const int ThesyconVid = 0x{tc.THESYCON_VID:04X};",
              f"        public const int ProtocolUsagePage = {tc.PROTOCOL_USAGE_PAGE};", ""]

    lines += ["        // GetSettings (0x710C) record index -> vendor field name",
              "        public static readonly Dictionary<int, string> Dx5Fields = new Dictionary<int, string>", "        {"]
    for i, n in sorted(vc.SETTINGS_FIELDS.items()):
        lines.append(f"            {{ {i}, {cs(n)} }},")
    lines += ["        };", ""]

    lines += ["        public static readonly Dictionary<string, string> FieldEnum = new Dictionary<string, string>", "        {"]
    for f, e in vc.FIELD_ENUM.items():
        lines.append(f"            {{ {cs(f)}, {cs(e)} }},")
    lines += ["        };", ""]

    lines += ["        public static readonly Dictionary<string, Dictionary<int, string>> Enums =",
              "            new Dictionary<string, Dictionary<int, string>>", "        {"]
    for e, table in vc.ENUMS.items():
        items = ", ".join(f"{{ {k}, {cs(v)} }}" for k, v in table.items())
        lines.append(f"            {{ {cs(e)}, new Dictionary<int, string> {{ {items} }} }},")
    lines += ["        };", ""]

    lines += ["        public static readonly Dictionary<int, int> SampleRates = new Dictionary<int, int>", "        {"]
    for k, v in vc.SAMPLE_RATES.items():
        lines.append(f"            {{ {k}, {v or 0} }},")
    lines += ["        };", ""]

    lines += [
        "        // DX1 II registers (toppingctl.py DX1_* constants)",
        f"        public const int Dx1OutState = 0x{tc.DX1_OUT_STATE:04X};",
        f"        public const int Dx1RegState = 0x{tc.DX1_REG_STATE[0]:02X}{tc.DX1_REG_STATE[1]:02X};",
        f"        public const int Dx1RegFilter = 0x{tc.DX1_REG_FILTER[0]:02X}{tc.DX1_REG_FILTER[1]:02X};",
        f"        public const int Dx1RegHighGain = 0x{tc.DX1_REG_HIGH_GAIN[0]:02X}{tc.DX1_REG_HIGH_GAIN[1]:02X};",
        f"        public const int Dx1RegInput = 0x{tc.DX1_REG_INPUT[0]:02X}{tc.DX1_REG_INPUT[1]:02X};",
        f"        public const int Dx1RegQueryCfg = 0x{tc.DX1_REG_QUERY_CFG[0]:02X}{tc.DX1_REG_QUERY_CFG[1]:02X};",
        f"        public const int Dx1RegQueryEnable = 0x{tc.DX1_REG_QUERY_ENABLE[0]:02X}{tc.DX1_REG_QUERY_ENABLE[1]:02X};",
        f"        public const int Dx1FieldMute = {tc.DX1_F_MUTE};",
        f"        public const int Dx1RegSwitchCfg = 0x{tc.DX1_REG_SWITCH_CFG[0]:02X}{tc.DX1_REG_SWITCH_CFG[1]:02X};",
        f"        public const int Dx1BlockLen = {tc.DX1_BLOCK_LEN};",
        f"        public const int Dx1FieldHpVol = {tc.DX1_F_HP_VOL}, Dx1FieldLoVol = {tc.DX1_F_LO_VOL}, Dx1FieldLoHpVol = {tc.DX1_F_LOHP_VOL};",
        f"        public const int Dx1VolRawMax = {tc.DX1_VOL_RAW_MAX};",
        "",
        "        // Control register, PEQ (toppingctl.py)",
        f"        public const int RegCtrl = 0x{tc.REG_CTRL:02X}, SubPower = 0x{tc.SUB_POWER:02X}, SubVolume = 0x{tc.SUB_VOLUME:02X}, SubGain = 0x{tc.SUB_GAIN:02X}, SubCommit = 0x{tc.SUB_COMMIT:02X};",
        f"        public const int SubPowerB4 = 0x{tc.SUB_POWER_B4:02X};",
        f"        public const int PeqFirst = 0x{tc.PEQ_FIRST:02X}, RegPreamp = 0x{tc.REG_PREAMP:02X}, RegCount = {tc.REG_COUNT}, BandCount = {tc.BAND_COUNT};",
        f"        public const int PreampScale = {tc.PREAMP_SCALE};",
        f"        public const double VolWarnDb = {tc.VOL_WARN_DB};",
        "        public static readonly Dictionary<string, int> FilterTypes = new Dictionary<string, int> { "
        + ", ".join(f"{{ {cs(k)}, {v} }}" for k, v in tc.FILTER_TYPES.items()) + " };",
        f"        public const int DefaultBandFreq = {tc.DEFAULT_BAND['freq']};",
        f"        public const double DefaultBandQ = {tc.DEFAULT_BAND['q']};",
        "",
        "        // Scene recall (scenes.py). Saving scenes is deliberately absent, as in toppingctl.",
        f"        public const int RecallC1 = 0x{scenes.RECALL['c1']:04X}, RecallC2 = 0x{scenes.RECALL['c2']:04X};",
        "",
        "        // DX5 II settings that setctl.py can write: field -> (command, confidence)",
        "        public static readonly Dictionary<string, KeyValuePair<int, string>> Dx5Settable =",
        "            new Dictionary<string, KeyValuePair<int, string>>",
        "        {",
    ]
    for f in sorted(set(vc.FIELD_ENUM) | set(sc.ALIASES) | {"balance"}):
        c, name, conf = sc.cmd_for(f)
        if not c or f in sc.NEVER:
            continue
        lines.append(f"            {{ {cs(f)}, new KeyValuePair<int, string>(0x{c:04X}, {cs(conf)}) }},")
    lines += [
        "        };",
        "    }",
        "}",
        "",
    ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
